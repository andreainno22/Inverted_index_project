def load_inverted_index(filepath):
    """
    Loads an inverted index from a text file.

    Each line in the file is expected to have a word followed by file:count entries,
    e.g. "word file1.txt:3 file2.txt:5"

    This function builds a dictionary where:
    - keys are words (in lowercase)
    - values are sets of filenames where the word appears
    """
    index = {}  # Initialize an empty dictionary to store the inverted index

    # Open the file for reading with UTF-8 encoding
    with open(filepath, 'r', encoding='utf-8') as f:
        for line in f:
            parts = line.strip().split()  # Remove whitespace and split by whitespace into parts
            if not parts:
                continue  # Skip empty lines
            word = parts[0].lower()  # The first part is the word, converted to lowercase for uniformity
            # From the remaining parts, extract only the filenames (before the colon ':')
            files = [entry.split(':')[0] for entry in parts[1:]]
            # Store the filenames in a set (to avoid duplicates) keyed by the word
            index[word] = set(files)

    return index  # Return the constructed inverted index dictionary


def search(index, query):
    """
    Searches the inverted index for documents containing all terms in the query.

    Args:
    - index: The inverted index dictionary (word -> set of filenames)
    - query: A string containing one or more search terms

    Returns:
    - A set of filenames that contain all query terms
    """
    terms = query.strip().lower().split()  # Normalize query: strip spaces, lowercase, split by space
    result = None  # Initialize result as None, will hold the intersection of file sets

    for term in terms:
        if term not in index:
            # If any term is not found in the index, no files can match all terms
            return set()
        if result is None:
            # For the first term, set result to the set of files containing it
            result = index[term]
        else:
            # For subsequent terms, take the intersection with the existing result
            result &= index[term]  # '&=' is set intersection update

    # If query was empty or terms were not found, return empty set
    return result or set()


